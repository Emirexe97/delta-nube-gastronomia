import { describe, expect, it } from "vitest";
import { fullMonthForRange } from "./finance-period";

describe("mes completo derivado del período financiero", () => {
  it.each([
    ["2026-10-01", "2026-10-31", "2026-10"],
    ["2026-04-01", "2026-04-30", "2026-04"],
    ["2026-02-01", "2026-02-28", "2026-02"],
    ["2024-02-01", "2024-02-29", "2024-02"],
    ["2000-02-01", "2000-02-29", "2000-02"],
    ["1900-02-01", "1900-02-28", "1900-02"],
    ["2026-10-08", "2026-10-08", ""],
    ["2026-10-01", "2026-10-30", ""],
    ["2026-10-01", "2026-11-01", ""],
    ["2024-02-01", "2024-02-28", ""],
    ["2026-02-01", "2026-02-29", ""],
    ["2026-10-09", "2026-10-08", ""],
    ["", "2026-10-31", ""],
    ["2026-10-01", "", ""],
    ["", "", ""],
    ["2026-13-01", "2026-13-31", ""],
    ["0000-01-01", "0000-01-31", ""],
    ["malformed", "2026-10-31", ""],
  ])("%s a %s → %s", (from, to, expected) => {
    expect(fullMonthForRange(from, to)).toBe(expected);
  });
});
